def run_row(out: str, *, cell: int, mu: float, lam: float, rho: float,
            n_substeps: int, frames: int) -> None:
    """Run one (cell, material, n_substeps) row and save its ledger series."""
    import mpm_energy as me

    cfg = cell_config(cell)
    inst = me.Instrument(mu=mu, lam=lam, rho=rho, n_substeps=n_substeps,
                         frame_dt=FRAME_DT, gravity=cfg["gravity"], quiet=True)
    inst.init_slab(centre=cfg["centre"], stretch=cfg["stretch"],
                   velocity=cfg["velocity"])

    pos_init = inst.m.F_x.to_numpy().copy()
    keys = ("ke", "ke_affine", "elastic", "gravity_pe", "total",
            "p_x", "p_y", "p_z", "l_x", "l_y", "l_z")
    series = {k: [] for k in keys}
    contact = []
    diverged, why = False, ""

    for f in range(frames + 1):
        led = inst.ledger()
        if not np.isfinite(led["total"]):
            diverged, why = True, f"non-finite energy at frame {f}"
            break
        for k in keys:
            series[k].append(led[k])
        c = inst.assert_no_contact()
        contact.append([c["min_index"], c["max_index"], float(c["ok"]),
                        c["clearance_m"], c["reach_m"]])
        if cfg["assert_no_contact"] and not (c["ok"] and c["sampling_safe"]):
            diverged, why = True, (
                f"CLEAN CELL VIOLATED at frame {f}: stencil {c['min_index']}.."
                f"{c['max_index']}, clearance {c['clearance_m']*1e3:.1f} mm vs "
                f"per-frame reach {c['reach_m']*1e3:.1f} mm")
            break
        if f < frames:
            try:
                inst.advance_frame(1)
            except Exception as e:                        # noqa: BLE001
                diverged, why = True, f"{type(e).__name__} at frame {f}"
                break

    np.savez_compressed(
        out,
        diverged=np.array(diverged), why=np.array(why),
        n_frames_done=np.array(len(series["total"])),
        pos_init=pos_init, pos_final=inst.m.F_x.to_numpy(),
        contact=np.array(contact, np.float64),
        meta=np.array(json.dumps(dict(
            cell=cell, mu=mu, lam=lam, rho=rho, n_substeps=n_substeps,
            substep_dt=inst.substep_dt, frame_dt=FRAME_DT, frames=frames,
            gravity=cfg["gravity"], p_mass=inst.p_mass, p_vol=inst.p_vol,
            dx=inst.dx, backend=inst.backend))),
        **{k: np.array(v, np.float64) for k, v in series.items()})


