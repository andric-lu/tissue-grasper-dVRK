def cell_config(cell: int) -> dict:
    if cell == 1:
        return dict(
            name="clean", gravity=0.0, assert_no_contact=True,
            # Domain centre. init_cube()'s slab is 0.3 x 0.3 x 0.05, so at the
            # centre its stencil spans indices ~19-44: sixteen clear cells from
            # the nearest special region at index 3.
            centre=[0.5, 0.5, 0.5], stretch=STRETCH, velocity=None,
            blurb="no contact, no gravity, known isochoric initial stretch")
    if cell == 3:
        # Lowest stencil node exactly on k = 3. base = int(z/dx - 0.5), so
        # z >= 3.5*dx = 54.7 mm puts base at 3; 55.5 mm leaves a little room
        # for float32. The `*= 0.1` band fires at k <= 3 and the wall condition
        # needs index < 3, so this arms the band and nothing else.
        z_bottom = 3.5 * DX + 0.0008
        return dict(
            name="band", gravity=0.0, assert_no_contact=False,
            centre=[0.5, 0.5, z_bottom + 0.025], stretch=1.0,
            velocity=[BAND_VELOCITY, 0.0, 0.0],
            blurb="floor band armed, gravity off, lateral drag only")
    if cell == 4:
        return dict(
            name="s9.6", gravity=9.8, assert_no_contact=False,
            centre=None, stretch=1.0, velocity=None,
            blurb="section 9.6 reproduced: init_cube as vendored, gravity, floor")
    raise ValueError(f"unknown cell {cell}")


