def _load_row(path: str) -> dict:
    if not os.path.isfile(path):
        return {"diverged": True, "why": "no file -- child died before writing"}
    d = np.load(path, allow_pickle=False)
    meta = json.loads(str(d["meta"]))
    out = {"diverged": bool(d["diverged"]), "why": str(d["why"]), **meta}
    for k in ("ke", "ke_affine", "elastic", "gravity_pe", "total",
              "p_x", "p_y", "p_z", "l_x", "l_y", "l_z"):
        out[k] = d[k]
    out["pos_init"] = d["pos_init"]
    out["pos_final"] = d["pos_final"]
    out["contact"] = d["contact"]
    if out["total"].size < meta["frames"] + 1:
        out["diverged"] = True
        out["why"] = out["why"] or f"stopped at frame {out['total'].size - 1}"
    return out


def report_cell(cell: int, label: str, rows: list, frames: int) -> dict:
    cfg = cell_config(cell)
    good = [r for r in rows if not r["diverged"]]
    print(f"\n  {'n_sub':>6} {'substep':>10} {'E(0)':>11} {'E(T)':>11} "
          f"{'dissipated':>11} {'frac':>7} {'per-transfer':>13} "
          f"{'per-second':>11} {'wall':>7}")
    print("  " + "-" * 96)
    for r in rows:
        if r["diverged"]:
            print(f"  {r['n_substeps']:>6} {r['substep_dt']*1e6:>8.1f}us "
                  f"{'DIVERGED':>11}   {r['why'][:52]}")
            continue
        e0, eT = r["total"][0], r["total"][-1]
        loss = e0 - eT
        n_tr = r["n_substeps"] * frames
        T = frames * FRAME_DT
        r["loss"] = loss
        print(f"  {r['n_substeps']:>6} {r['substep_dt']*1e6:>8.1f}us "
              f"{e0:>11.5f} {eT:>11.5f} {loss:>11.5f} "
              f"{loss/max(abs(e0),1e-30)*100:>6.2f}% {loss/n_tr:>13.3e} "
              f"{loss/T:>11.4f} {r['wall']:>6.1f}s")

    if len(good) < 3:
        print("\n  Fewer than three rows survived; no exponent can be fitted.")
        return {"cell": cell, "label": label, "verdict": "INSUFFICIENT"}

    # THE SHARED-CLOUD ASSERTION. Every row must start from an identical
    # particle cloud or the pairwise field comparison below is meaningless.
    ref = good[0]["pos_init"]
    for r in good[1:]:
        if not np.array_equal(r["pos_init"], ref):
            raise SystemExit(
                f"FATAL: row n={r['n_substeps']} started from a different "
                "particle cloud. The refinement ladder assumes particle i is "
                "the same particle in every row, which held because Taichi's "
                "RNG is seeded 0 in every process. See section 9.5/9.6.")

    # ENERGY OVER THE WHOLE TRAJECTORY, not just the endpoint. If dissipation
    # were an endpoint artifact -- one late event rather than a steady drain --
    # these quarters would not be comparable.
    print(f"\n  Cumulative dissipation as a fraction of E(0), through the run:")
    print(f"  {'n_sub':>6} " + " ".join(f"{int(100*q):>7}%" for q in (.25, .5, .75, 1.)))
    for r in good:
        e = r["total"]
        e0 = e[0]
        qs = [(e0 - e[int(round(q * (len(e) - 1)))]) / max(abs(e0), 1e-30)
              for q in (.25, .5, .75, 1.0)]
        print(f"  {r['n_substeps']:>6} " + " ".join(f"{v*100:>7.2f}" for v in qs))

    # THE TERM-BY-TERM BREAKDOWN AT T. This is the table that connects section 9.6
    # to this one: its probe was KE alone, and KE alone is printed here next to
    # the budget it belongs to. If KE falls across the ladder while the TOTAL
    # dissipation also falls, then "KE fell, so damping rose" was reading a
    # redistribution as a loss.
    print(f"\n  Where the energy is at T = {frames * FRAME_DT:.3f} s "
          f"(section 9.6's probe was the KE column alone):")
    print(f"  {'n_sub':>6} {'KE':>11} {'KE_affine':>11} {'elastic':>11} "
          f"{'PE_grav':>11} {'TOTAL':>11}")
    for r in good:
        print(f"  {r['n_substeps']:>6} {r['ke'][-1]:>11.5f} "
              f"{r['ke_affine'][-1]:>11.5f} {r['elastic'][-1]:>11.5f} "
              f"{r['gravity_pe'][-1]:>11.5f} {r['total'][-1]:>11.5f}")

    # SUCCESSIVE PAIRS, no privileged finest row. section 9.6 measured every row
    # against its finest one while arguing that the finest was the most
    # over-damped -- which makes the reference the least trustworthy row in the
    # table. Adjacent differences do not need a reference at all: if they shrink
    # geometrically the scheme is converging on something, and the ratio names
    # the observed order.
    print(f"\n  Refinement ladder, successive pairs (no reference row):")
    print(f"  {'pair':>12} {'RMS diff':>12} {'as % of disp':>13} {'order p':>9}")
    deltas = []
    for a, b in zip(good, good[1:]):
        d = float(np.sqrt(((a["pos_final"].astype(np.float64)
                            - b["pos_final"].astype(np.float64)) ** 2).sum(axis=1).mean()))
        disp = float(np.sqrt(((b["pos_final"].astype(np.float64)
                               - b["pos_init"].astype(np.float64)) ** 2).sum(axis=1).mean()))
        deltas.append((f"{a['n_substeps']}/{b['n_substeps']}", d, disp))
    for i, (name, d, disp) in enumerate(deltas):
        # Observed order: how many times smaller this pair's difference is than
        # the previous pair's, in powers of two. Positive and roughly constant
        # is convergence at that order; zero or negative means the rows are not
        # approaching each other at all, whatever the finest one says.
        p = np.log2(deltas[i - 1][1] / d) if i > 0 and d > 0 else float("nan")
        order = f"{p:>9.2f}" if np.isfinite(p) else f"{'-':>9}"
        print(f"  {name:>12} {d * 1e3:>10.4f}mm "
              f"{d / max(disp, 1e-12) * 100:>12.2f}% {order}")

    # THE VERDICT, FROM THE DECAY RATE RATHER THAN THE LOSS FRACTION.
    #
    # WHY NOT THE FRACTION. A fraction of E(0) cannot exceed 1, and the clean
    # cell reaches 78%. Once a row is that far along, the next row cannot lose
    # proportionally more even if its dissipation is genuinely stronger, so the
    # fitted exponent is squeezed toward zero by the ceiling and not by the
    # physics. That would bias this study TOWARD its own conclusion, which is
    # the one direction a study must not be biased.
    #
    # The decay constant k = -ln(E(T)/E(0)) / T has no ceiling: it is the
    # e-folding rate, and it keeps growing however much energy is already gone.
    # Where nothing is saturated the two measures agree to two decimals (cell 4
    # loses only 1-5%, and its q_loss and q_rate match), which is what makes it
    # safe to prefer the one that also works where they do not.
    dts = np.array([r["substep_dt"] for r in good])
    losses = np.array([r["loss"] for r in good])
    T = frames * FRAME_DT
    rates = np.array([
        -np.log(max(r["total"][-1], 1e-300) / r["total"][0]) / T
        if r["total"][0] > 0 and r["total"][-1] > 0 else np.nan
        for r in good])
    fit_loss = EL.fit_scaling_exponent(dts, losses)
    fit = EL.fit_scaling_exponent(dts, rates)
    col = EL.normalisation_collapse(dts, losses, total_time=T)
    code, why = EL.verdict(fit["q"], fit["r2"], col["collapses"],
                           collapse_ratio=col["collapse_ratio"],
                           span=float(dts.max() / dts.min()))
    print(f"\n  decay rate k = -ln(E(T)/E(0))/T:  "
          + "  ".join(f"{r:.4f}/s" for r in rates))
    print(f"  k(dt) ~ dt^q:     q = {fit['q']:+.3f}   r2 = {fit['r2']:.4f}   "
          f"({fit['n']} rows, {fit['n_dropped']} dropped)   <- the verdict")
    print(f"  loss(dt) ~ dt^q:  q = {fit_loss['q']:+.3f}   "
          f"r2 = {fit_loss['r2']:.4f}   (ceiling-limited where loss is large)")
    print(f"  collapse spread (max/min, 1.0 is perfect):  "
          f"per transfer {col['spread_per_transfer']:.2f}   "
          f"per second {col['spread_per_time']:.2f}   -> {col['collapses']}")
    print(f"\n  VERDICT [{cell} {cfg['name']}, {label}]: {code}")
    print(f"    {why}")

    # MOMENTUM IS ONLY A CHECK WHERE IT IS CONSERVED. Cell 1 is closed: no
    # gravity, no contact, zero initial momentum, and nothing in the solver can
    # create any. Cells 3 and 4 have a floor and a gravity field, which exchange
    # momentum with the world by design -- reporting their nonzero momentum as
    # a fault was wrong, and the first version of this did exactly that.
    if cfg["gravity"] == 0.0 and cfg["assert_no_contact"]:
        # Relative, not absolute. The scale is the momentum the body would have
        # if all its remaining kinetic energy were one coherent translation;
        # a drift is only meaningful against that.
        worst = 0.0
        for r in good:
            p = np.hypot(np.hypot(r["p_x"][-1], r["p_y"][-1]), r["p_z"][-1])
            mass = r["p_mass"] * 24000.0
            scale = np.sqrt(2.0 * max(r["ke"][-1], 1e-30) * mass)
            worst = max(worst, p / max(scale, 1e-30))
        print(f"    linear momentum at T, worst row: {worst:.2e} of the "
              "coherent-translation scale "
              + ("(float32 noise, as it must be)" if worst < 1e-4 else
                 "(NOT noise -- the solver created momentum; investigate)"))
    return {"cell": cell, "label": label, "verdict": code, "q": fit["q"],
            "r2": fit["r2"], "collapse": col["collapses"], "why": why}


