def dispatch(cmd, timeout=ROW_TIMEOUT_S):
    t0 = time.time()
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
        return proc.returncode, time.time() - t0, proc.stderr
    except subprocess.TimeoutExpired:
        return -1, time.time() - t0, f"timed out after {timeout}s"


def run_selftest(mu, lam, rho, n_adv, scratch) -> bool:
    print("=" * 96)
    print("SELFTEST -- the instrument, before any result from it counts".center(96))
    print("=" * 96)
    out = os.path.join(scratch, "selftest_basic.json")
    rc, wall, err = dispatch([sys.executable, os.path.abspath(__file__),
                              "--child", "selftest-basic", "--out", out,
                              "--material", f"{mu:.10g}", f"{lam:.10g}", f"{rho:.10g}",
                              "--row", str(n_adv)])
    if rc != 0 or not os.path.isfile(out):
        print(f"  basic selftest child failed (rc={rc})\n{err[-2000:]}")
        return False
    res = json.load(open(out))
    ok = True
    for name in ("gravity_off", "rigid_translation", "affine_velocity",
                 "split_matches_solver",
                 "boundary_inert_in_clean_cell"):
        c = res[name]
        ok &= c["passed"]
        print(f"  [{'PASS' if c['passed'] else 'FAIL'}] {name:<22} {c['detail']}")

    # CHECK 4, one process per dt. No stress means no CFL, so the ladder can be
    # much wider than the real cells' -- a factor of 64 here.
    print(f"\n  Zero-stiffness transfer test (mu = lambda = 0: nothing but the "
          f"transfers can\n  remove energy). If loss per transfer is flat in dt, "
          f"dissipation counts transfers.")
    print(f"  {'n_sub':>6} {'substep':>10} {'transfers':>10} {'E(0)':>12} "
          f"{'loss':>12} {'loss/transfer':>14}")
    rows = []
    for n in (4, 16, 64, 256):
        o = os.path.join(scratch, f"selftest_transfer_{n}.json")
        rc, wall, err = dispatch([sys.executable, os.path.abspath(__file__),
                                  "--child", "selftest-transfer", "--out", o,
                                  "--row", str(n), "--material", "0", "0",
                                  f"{rho:.10g}"])
        if rc != 0 or not os.path.isfile(o):
            print(f"  {n:>6}  child failed (rc={rc}): {err.strip()[-200:]}")
            continue
        r = json.load(open(o))
        rows.append(r)
        print(f"  {r['n_substeps']:>6} {r['substep_dt']*1e6:>8.1f}us "
              f"{r['n_transfers']:>10} {r['e0']:>12.6e} {r['loss']:>12.5e} "
              f"{r['loss_per_transfer']:>14.5e}")
    if len(rows) >= 3:
        dts = np.array([r["substep_dt"] for r in rows])
        loss = np.array([r["loss"] for r in rows])
        fit = EL.fit_scaling_exponent(dts, loss)
        col = EL.normalisation_collapse(dts, loss, rows[0]["sim_time"])
        code, why = EL.verdict(fit["q"], fit["r2"], col["collapses"],
                           collapse_ratio=col["collapse_ratio"])
        print(f"\n  pure-transfer loss(dt) ~ dt^q:  q = {fit['q']:+.3f}  "
              f"r2 = {fit['r2']:.4f}  -> {code}")
        print(f"    {why}")
    print(f"\n  SELFTEST {'PASSED' if ok else 'FAILED'} -- "
          + ("the instrument is sound; results below are readable."
             if ok else "do not read any result below."))
    return ok


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__.split("\n")[1],
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--frames", type=int, default=60,
                    help="recorded frames per row (60 x 12.5 ms = 0.75 s, "
                         "matching section 9.6)")
    ap.add_argument("--cells", type=int, nargs="+", default=list(CELLS),
                    choices=list(CELLS))
    ap.add_argument("--materials", default="both", choices=("both", "soft", "stiff"))
    ap.add_argument("--multipliers", type=float, nargs="+", default=None)
    ap.add_argument("--selftest", action="store_true",
                    help="run the instrument checks and stop")
    ap.add_argument("--no-selftest", action="store_true",
                    help="skip the gate (for iterating; never for a result)")
    # Child-only. Presence means "you are one row"; see the module docstring.
    ap.add_argument("--child", default=None, help=argparse.SUPPRESS)
    ap.add_argument("--out", default="", help=argparse.SUPPRESS)
    ap.add_argument("--row", type=int, default=None, help=argparse.SUPPRESS)
    ap.add_argument("--cell", type=int, default=1, help=argparse.SUPPRESS)
    ap.add_argument("--material", type=float, nargs=3, default=None,
                    help=argparse.SUPPRESS)
    args = ap.parse_args(argv)

    # THE CHILD BRANCH -- never dispatches, so recursion cannot happen.
    if args.child:
        mu, lam, rho = args.material
        if args.child == "row":
            run_row(args.out, cell=args.cell, mu=mu, lam=lam, rho=rho,
                    n_substeps=args.row, frames=args.frames)
        elif args.child == "selftest-basic":
            json.dump(selftest_basic(mu, lam, rho, args.row), open(args.out, "w"))
        elif args.child == "selftest-transfer":
            json.dump(selftest_transfer(args.row, rho), open(args.out, "w"))
        else:
            raise SystemExit(f"unknown child kind {args.child}")
        return 0

    # THE PARENT. Must not import mpm_energy or mpm3d -- that would run
    # ti.init() and compile kernels in the very process the children exist to
    # isolate. Only MPM.config (which imports nothing) is touched, at the top.
    import mpm_adapter
    mats = {s: mpm_adapter.sample_episode_material(s) for s in (0, 1)}
    by_ratio = sorted(mats.items(), key=lambda kv: kv[1][1] / kv[1][0])
    labelled = [("soft-lambda", by_ratio[0][1]), ("stiff-lambda", by_ratio[1][1])]
    if args.materials == "soft":
        labelled = labelled[:1]
    elif args.materials == "stiff":
        labelled = labelled[1:]

    print("=" * 96)
    print("MPM ENERGY AUDIT -- section 9.7".center(96))
    print("=" * 96)
    print(f"dx = 1/{n_grid} = {DX*1e3:.3f} mm, frame_dt = {FRAME_DT*1e3:.2f} ms, "
          f"{args.frames} frames = {args.frames*FRAME_DT:.3f} s per row")
    print("Budget: KE_particle + KE_affine + Psi_elastic + PE_gravity, over all "
          "24,000 particles, float64.")
    print("Verdict: the exponent q in (dissipation over fixed T) ~ dt^q.  "
          "-1 per transfer, 0 per second, +1 convergent.")

    t0 = time.time()
    scratch = tempfile.mkdtemp(prefix="energy_audit_")
    summary = []
    try:
        mu0, lam0, rho0 = labelled[0][1]
        n_adv0 = int(np.ceil(FRAME_DT / materials.suggested_substep_dt(
            mu0, rho0, DX, safety=BASE_SAFETY, lam=lam0)))
        if not args.no_selftest:
            if not run_selftest(mu0, lam0, rho0, n_adv0, scratch) and not args.selftest:
                print("\nSELFTEST FAILED -- refusing to run the cells. D1 is a gate.")
                return 1
        if args.selftest:
            return 0

        mults = tuple(args.multipliers) if args.multipliers else MULTIPLIERS
        for cell in args.cells:
            cfg = cell_config(cell)
            for label, (mu, lam, rho) in labelled:
                n_adv = int(np.ceil(FRAME_DT / materials.suggested_substep_dt(
                    mu, rho, DX, safety=BASE_SAFETY, lam=lam)))
                ns = sorted({max(1, int(round(n_adv * m))) for m in mults})
                print(f"\n{'=' * 96}")
                print(f"CELL {cell} ({cfg['name']}) -- {cfg['blurb']}")
                print(f"{label}: mu = {mu:.0f} Pa, lambda = {lam:.0f} Pa, "
                      f"rho = {rho:.1f}, lambda/mu = {lam/mu:.0f}; "
                      f"advisory {n_adv} substeps/frame at safety={BASE_SAFETY}")
                print("=" * 96)
                rows = []
                for n in ns:
                    path = os.path.join(scratch, f"c{cell}_{label}_{n:05d}.npz")
                    rc, wall, err = dispatch(
                        [sys.executable, os.path.abspath(__file__),
                         "--child", "row", "--out", path, "--cell", str(cell),
                         "--row", str(n), "--frames", str(args.frames),
                         "--material", f"{mu:.10g}", f"{lam:.10g}", f"{rho:.10g}"])
                    r = _load_row(path)
                    if rc != 0 and not r["diverged"]:
                        r["diverged"], r["why"] = True, f"child exited {rc}"
                    r.setdefault("n_substeps", n)
                    r.setdefault("substep_dt", FRAME_DT / n)
                    r["wall"] = wall
                    if r["diverged"] and not r["why"]:
                        r["why"] = err.strip().splitlines()[-1][:80] if err else "?"
                    rows.append(r)
                summary.append(report_cell(cell, label, rows, args.frames))
                for f in os.listdir(scratch):
                    if f.startswith(f"c{cell}_{label}_"):
                        os.remove(os.path.join(scratch, f))
    finally:
        for f in os.listdir(scratch):
            os.remove(os.path.join(scratch, f))
        os.rmdir(scratch)

    print(f"\n{'=' * 96}")
    print(f"{'cell':>6} {'material':>14} {'verdict':>14} {'q':>8} {'r2':>7} {'collapse':>14}")
    for s in summary:
        if s.get("q") is None:
            print(f"{s['cell']:>6} {s['label']:>14} {s['verdict']:>14}")
        else:
            print(f"{s['cell']:>6} {s['label']:>14} {s['verdict']:>14} "
                  f"{s['q']:>+8.3f} {s['r2']:>7.4f} {s['collapse']:>14}")
    print(f"\nTotal wall time: {time.time() - t0:.1f}s")
    print("Record the outcome in DECISION_LOG.md section 9.7, and amend section 9.6 to "
          "match.")
    return 0


