#!/usr/bin/env python3
"""energy_audit.py -- does MPM dissipation count transfers, or count seconds?

Run on the HOST (Taichi/Metal, see CLAUDE.md):

    conda activate tissue-host
    python host/energy_audit.py --selftest             # the instrument, ~1 min
    python host/energy_audit.py                        # cells 1, 3, 4
    python host/energy_audit.py --cells 1 --materials soft --frames 12   # quick

THE QUESTION THIS ANSWERS
-------------------------
DECISION_LOG.md section 9.6 concluded that MPM's particle-grid transfers dissipate
energy PER TRANSFER rather than per unit of simulated time, and therefore that
refining the substep at a fixed grid cannot converge. That conclusion is now
load-bearing: CLAUDE.md tells future work not to refine, and section 9.6 uses it to
declare safety_strain non-comparable between episodes.

It rests on one probe -- specific kinetic energy of a 3,000-particle subset at a
fixed simulated time, falling monotonically across the sweep
(substep_study.py:216) -- and that probe cannot carry it:

  * KE IS NOT THE BUDGET. The rows settled under gravity, so KE was pumped by
    gravitational release and drained by contact, elasticity and the transfers
    at once. A falling KE is equally consistent with "damped harder" and
    "converted to strain energy sooner". Psi and PE were never measured.
  * CONTACT WAS LIVE THROUGHOUT. Every row sat on the floor, so the `*= 0.1`
    band and the `bound = 3` wall condition were both firing.
  * THE FINEST ROW WAS THE REFERENCE, while being, by section 9.6's own argument,
    the most over-damped row in the sweep.
  * THE SUBSET WAS THE WRONG SET. mpm_adapter rule 2 already says so for
    safety_strain, and it is equally true of an energy.

There is also a specific reason to suspect the attribution is BACKWARDS. The
`*= 0.1` floor band (mpm3d.py:274-276) multiplies grid velocity once per substep
with no dt scaling -- that is the literal definition of a transfer-count sink,
far more obviously than the P2G/G2P round trip. Section 9.6 dismissed it because
the band touches [0] and [1] and never [2], yet the stiff material's VERTICAL
error was the largest in the sweep at 61.7%. That material has lambda/mu = 754.
Near incompressibility, suppressing lateral flow at the base suppresses vertical
settling almost rigidly, so the material with the strongest coupling showing the
largest vertical error is what the floor hypothesis PREDICTS. Cell 3 exists to
settle that.

WHAT IS MEASURED
----------------
The closed budget, over all 24,000 particles, in float64:

    E = KE_particle + KE_affine + Psi_elastic + PE_gravity

See src/energy_ledger.py for why the affine term is not optional and why the
existing `strain_energy_neohookean` is exactly the potential conjugate to the
solver's stress.

THE VERDICT IS ONE EXPONENT
---------------------------
Fit (total dissipation over a FIXED simulated time T) ~ dt^q.

    q ~ -1   per TRANSFER      section 9.6 confirmed; refinement cannot converge
    q ~  0   per unit TIME     section 9.6's mechanism is wrong; loss is a rate
    q ~ +1   truncation error  section 9.6 FALSIFIED; refinement does converge

q ~ +1 is a live outcome, not a strawman: if the non-affine velocity content
each transfer destroys is regenerated by inter-transfer motion of size |v|*dt,
the loss per transfer goes as dt^2 and the total over T goes as dt. The
predictions were written down before the runs; see DECISION_LOG.md section 9.7.

THREE CELLS
-----------
  1  clean   slab at the domain centre, gravity OFF, an exactly known isochoric
             initial stretch, and every stencil node provably five cells clear
             of any special region. Nothing but the transfers can remove energy.
  3  band    slab placed so its lowest stencil node sits exactly on k = 3,
             gravity off, given a lateral velocity. The `*= 0.1` sink is then
             the only boundary term firing and its dt scaling is measurable.
  4  s9.6    the section 9.6 configuration reproduced -- init_cube() as vendored,
             gravity on, floor contact -- now under the full ledger, so the old
             KE-only numbers can be re-read against a closed budget.

ONE PROCESS PER ROW
-------------------
Same constraint as the collector and the substep study, with one more constant:
Taichi bakes `dt`, `p_mass` AND `gravity` into kernels at compile time, because
Boundary() reads gravity as a plain Python global inside a @ti.func. `--child`
marks a child and, exactly like `--index` in mpm_adapter.py, makes recursion
structurally impossible -- the parent always passes it, and a process holding it
never dispatches. Children run with check=False: a diverged row is a RESULT.
"""

