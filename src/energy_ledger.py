def fit_scaling_exponent(dt: Sequence[float],
                         loss: Sequence[float]) -> Dict[str, float]:
    """Least-squares fit of  loss ~ A * dt^q  in log-log space.

    Returns q, the prefactor, and r2. r2 is reported because a bad fit is a
    result in itself: if the points do not lie on a power law, no single
    exponent describes the dissipation and the verdict must say "ambiguous"
    rather than quote a slope nobody should trust.

    Rows with non-positive loss are dropped and counted. A negative measured
    dissipation is not noise to be averaged away -- it means energy was
    CREATED, which for this solver would be a genuine finding, so it is
    surfaced rather than swallowed.
    """
    dt = np.asarray(dt, np.float64)
    loss = np.asarray(loss, np.float64)
    if dt.shape != loss.shape:
        raise ValueError(f"dt {dt.shape} and loss {loss.shape} must match")
    good = np.isfinite(dt) & np.isfinite(loss) & (dt > 0) & (loss > 0)
    n_dropped = int((~good).sum())
    if good.sum() < 2:
        return {"q": float("nan"), "log_a": float("nan"), "r2": float("nan"),
                "n": int(good.sum()), "n_dropped": n_dropped}

    lx, ly = np.log(dt[good]), np.log(loss[good])
    q, log_a = np.polyfit(lx, ly, 1)
    resid = ly - (q * lx + log_a)
    ss_tot = ((ly - ly.mean()) ** 2).sum()
    r2 = 1.0 - (resid ** 2).sum() / ss_tot if ss_tot > 0 else 1.0
    return {"q": float(q), "log_a": float(log_a), "r2": float(r2),
            "n": int(good.sum()), "n_dropped": n_dropped}


def normalisation_collapse(dt: Sequence[float], loss: Sequence[float],
                           total_time: float) -> Dict[str, float]:
    """Which normalisation makes the ladder collapse: per transfer, or per time?

    SCALE-FREE ON PURPOSE. Section 9.6's own postmortem records that a magnitude
    threshold ("KE fell more than 10x") gave one material the wrong advice, and
    that the fix was to test a shape (monotonicity) rather than a size. Same
    idea here: the mechanism is named by whichever normalisation has the
    smaller max/min spread across the ladder, and nobody has to pick a cutoff
    for that comparison to mean something.

        per transfer:  loss / N   where N = total_time / dt
        per time:      loss / total_time

    `spread` is max/min, so 1.0 is a perfect collapse and larger is worse.
    """
    dt = np.asarray(dt, np.float64)
    loss = np.asarray(loss, np.float64)
    good = np.isfinite(dt) & np.isfinite(loss) & (dt > 0) & (loss > 0)
    if good.sum() < 2:
        return {"spread_per_transfer": float("nan"),
                "spread_per_time": float("nan"),
                "collapse_ratio": float("nan"), "collapses": "insufficient"}
    n_transfers = total_time / dt[good]
    per_transfer = loss[good] / n_transfers
    per_time = loss[good] / total_time
    s_tr = float(per_transfer.max() / per_transfer.min())
    s_ti = float(per_time.max() / per_time.min())
    # How many times tighter the winning normalisation is. 1.0 means the two
    # descriptions are equally good and the diagnostic has decided nothing.
    ratio = max(s_tr, s_ti) / max(min(s_tr, s_ti), 1e-30)
    return {"spread_per_transfer": s_tr, "spread_per_time": s_ti,
            "collapse_ratio": float(ratio),
            "collapses": "per_transfer" if s_tr < s_ti else "per_time"}


def verdict(q: float, r2: float, collapse: Optional[str] = None,
            r2_floor: float = 0.9, collapse_ratio: Optional[float] = None,
            decisive: float = 3.0,
            span: Optional[float] = None) -> Tuple[str, str]:
    """(code, one-line reason) for a fitted exponent.

    ORDER MATTERS HERE, AND GETTING IT WRONG COST TWO WRONG LABELS. The band is
    decided from q FIRST; the r2 gate can then either annotate that verdict or
    withdraw it, but it must never substitute a different one. An earlier
    version let the degenerate-fit fallback return RATE_LIKE outright whenever
    the collapse diagnostic preferred "per time", which relabelled a measured
    q = +0.24 as "independent of dt to within a few percent" -- the same
    overstatement, arriving by a second route after the first was closed.
    """
    if not np.isfinite(q):
        return "AMBIGUOUS", "no usable rows in the ladder"

    # QUOTE THE MEASURED FACTOR, NOT JUST THE BAND. Across a ladder spanning
    # `span` in dt, the per-transfer hypothesis predicts the dissipation changes
    # by `span`, and a pure rate predicts it does not change at all. Saying
    # which of those the data is near, in the same units, is worth more than any
    # label -- and it is checkable by hand from the table above it.
    measured = ""
    if span and span > 1:
        measured = (f"  Across this {span:.0f}x ladder: measured "
                    f"{span ** abs(q):.1f}x, per-transfer predicts {span:.0f}x, "
                    f"a pure rate predicts 1x.")
    if q <= Q_PER_TRANSFER:
        code, why = "PER_TRANSFER", (
            f"q = {q:+.2f}: dissipation grows nearly in proportion to the "
            "number of transfers. Refining dt cannot converge.")
    elif q >= Q_CONVERGENT:
        code, why = "CONVERGENT", (
            f"q = {q:+.2f}: dissipation vanishes as dt -> 0, which is ordinary "
            "truncation error. Refining dt DOES converge.")
    elif abs(q) <= Q_RATE_LIKE:
        code, why = "RATE_LIKE", (
            f"q = {q:+.2f}: dissipation is independent of dt to within a few "
            "percent, i.e. a rate in simulated time and not a transfer count.")
    else:
        code, why = "INTERMEDIATE", (
            f"q = {q:+.2f}: neither mechanism on its own. Dissipation "
            + ("RISES as the substep shrinks, so it is not pure truncation "
               "error, but far too weakly to be a per-transfer count."
               if q < 0 else
               "FALLS as the substep shrinks, so refinement helps, but too "
               "weakly to be clean first-order convergence."))
    why += measured

    # THE POWER-LAW GATE. An exponent read off points that do not lie on a power
    # law is a number, not a finding -- so the default is to withdraw the
    # verdict. The one exception is a series so FLAT that r2 is degenerate
    # rather than damning: with loss ~ constant there is almost no variance to
    # explain, and r2 collapses however well the description fits. "The loss did
    # not move across a factor of 64 in dt" is a strong result, not an absent
    # one, so where the scale-free collapse diagnostic is decisive the verdict
    # stands and says why it is on thinner evidence.
    if np.isfinite(r2) and r2 < r2_floor:
        if collapse_ratio is not None and collapse_ratio >= decisive and collapse:
            why += (f"  CAUTION: the power-law fit is poor (r2 = {r2:.3f}), so "
                    f"the exponent is weak evidence; the scale-free collapse "
                    f"diagnostic independently prefers '{collapse}' by "
                    f"{collapse_ratio:.0f}x.")
        else:
            return "AMBIGUOUS", (
                f"loss(dt) is not a power law (r2 = {r2:.3f} < {r2_floor}) and "
                "the collapse diagnostic does not settle it either; no single "
                "mechanism describes this ladder")

    # The collapse diagnostic only ever chooses between "per transfer" and
    # "per time", so it can confirm or contradict those two verdicts and has
    # nothing to say about the ones in between. Reporting it as a disagreement
    # with INTERMEDIATE or CONVERGENT would manufacture a conflict out of a
    # question it was never asked.
    if collapse in ("per_transfer", "per_time") and code in ("PER_TRANSFER",
                                                             "RATE_LIKE"):
        agrees = ((code == "PER_TRANSFER" and collapse == "per_transfer")
                  or (code == "RATE_LIKE" and collapse == "per_time"))
        why += ("  The collapse diagnostic agrees." if agrees else
                f"  NOTE: the collapse diagnostic prefers '{collapse}', which "
                "does not agree -- treat the verdict as provisional.")
    return code, why


# --------------------------------------------------------------------------

def _require_shape(a: np.ndarray, shape, name: str) -> None:
    if a.ndim != len(shape) or any(
            s is not None and a.shape[i] != s for i, s in enumerate(shape)):
        want = "(" + ", ".join("N" if s is None else str(s) for s in shape) + ")"
        raise ValueError(f"{name} must be {want}, got {a.shape}")
